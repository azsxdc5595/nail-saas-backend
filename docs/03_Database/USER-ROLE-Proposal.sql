-- USER_ROLE table proposal
-- Status: Proposed; do not execute until the role scope and grant/revocation
-- workflow are approved. This file is not part of the authoritative schema rebuild.

CREATE TABLE USER_ROLE (
    USER_ID NUMBER NOT NULL,
    ROLE_CODE VARCHAR2(30) NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    GRANTED_BY_USER_ID NUMBER,
    CREATE_TIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_TIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_ROLE PRIMARY KEY (USER_ID, ROLE_CODE),
    CONSTRAINT FK_USER_ROLE_USER
        FOREIGN KEY (USER_ID) REFERENCES USER_ACCOUNT (USER_ID),
    CONSTRAINT FK_USER_ROLE_GRANTED_BY
        FOREIGN KEY (GRANTED_BY_USER_ID) REFERENCES USER_ACCOUNT (USER_ID),
    CONSTRAINT CK_USER_ROLE_CODE
        CHECK (ROLE_CODE IN ('MEMBER', 'MANICURIST', 'SHOP_MANAGER', 'ADMIN')),
    CONSTRAINT CK_USER_ROLE_ACTIVE
        CHECK (IS_ACTIVE IN (0, 1))
);

COMMENT ON TABLE USER_ROLE IS '使用者系統角色指派與授權狀態（提案）';
COMMENT ON COLUMN USER_ROLE.USER_ID IS '使用者帳戶識別碼';
COMMENT ON COLUMN USER_ROLE.ROLE_CODE IS '系統角色代碼：MEMBER 一般用戶、MANICURIST 美甲師、SHOP_MANAGER 店長或老闆、ADMIN 系統管理員';
COMMENT ON COLUMN USER_ROLE.IS_ACTIVE IS '角色指派是否有效：1 有效、0 停用';
COMMENT ON COLUMN USER_ROLE.GRANTED_BY_USER_ID IS '授予角色的操作者；系統初始指派可為 NULL';
COMMENT ON COLUMN USER_ROLE.CREATE_TIME IS '角色指派建立時間';
COMMENT ON COLUMN USER_ROLE.UPDATE_TIME IS '角色指派最後異動時間';
